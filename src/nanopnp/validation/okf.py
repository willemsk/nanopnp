"""Build the documentation navigation of an OKF bundle from its index pages."""

from __future__ import annotations

import json
import re
from collections.abc import Sequence
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[3]

INDEX_ENTRY = re.compile(r"^\*[ \t]+\[(.+?)\]\(([^)\s#]+)\)", re.MULTILINE)


def _nav_title(label: str) -> str:
    return json.dumps(re.sub(r"[*`]", "", label), ensure_ascii=False)


def navigation(
    root: Path, prefix: str, title: str, opening: Sequence[str], closing: Sequence[str] = ()
) -> list[str]:
    """Return the documentation navigation of the bundle, read from its index pages.

    Parameters
    ----------
    root
        The bundle's directory, holding the ``index.md`` the navigation is read from.
    prefix
        The bundle's path in the documentation tree.
    title
        The navigation section's title.
    opening, closing
        Entries placed before and after the index's listing, as written in ``mkdocs.yml``.
    """
    lines = [f"- {title}:", *(f"    - {entry}" for entry in opening)]
    for label, target in INDEX_ENTRY.findall((root / "index.md").read_text(encoding="utf-8")):
        directory = Path(target).parent
        if Path(target).name != "index.md":
            lines.append(f"    - {_nav_title(label)}: {prefix}/{target}")
            continue
        lines += [f"    - {_nav_title(label)}:", f"        - {prefix}/{target}"]
        listing = (root / target).read_text(encoding="utf-8")
        for name, page in INDEX_ENTRY.findall(listing):
            lines.append(f"        - {_nav_title(name)}: {prefix}/{(directory / page).as_posix()}")
    lines += [f"    - {entry}" for entry in closing]
    return lines


def splice_navigation(config: str, lines: list[str], bundle: str) -> str:
    """Return ``config`` with ``bundle``'s navigation block replaced by ``lines``."""
    begin = f"# BEGIN {bundle} navigation (generated by docs/scripts/generate.py)"
    end = f"# END {bundle} navigation"
    head, found, rest = config.partition(begin)
    if not found:
        raise ValueError(f"mkdocs.yml has no {begin!r} marker")
    _, _, tail = rest.partition(end)
    indent = head[head.rfind("\n") + 1 :]
    body = "".join(f"{indent}{line}\n" for line in lines)
    return f"{head}{begin}\n{body}{indent}{end}{tail}"
