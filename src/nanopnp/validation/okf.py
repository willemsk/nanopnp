"""Build the documentation navigation from the knowledge bundle's index pages."""

from __future__ import annotations

import json
import re
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[3]

NAV_BEGIN = "# BEGIN knowledge navigation (generated by docs/scripts/generate.py)"

NAV_END = "# END knowledge navigation"

INDEX_ENTRY = re.compile(r"^\*[ \t]+\[(.+?)\]\(([^)\s#]+)\)", re.MULTILINE)


def _nav_title(label: str) -> str:
    return json.dumps(re.sub(r"[*`]", "", label), ensure_ascii=False)


def navigation(root: Path, prefix: str) -> list[str]:
    """Return the documentation navigation of the bundle, read from its index pages."""
    lines = ["- Knowledge base:", f"    - {prefix}/index.md"]
    for label, target in INDEX_ENTRY.findall((root / "index.md").read_text(encoding="utf-8")):
        directory = Path(target).parent
        if Path(target).name != "index.md":
            lines.append(f"    - {_nav_title(label)}: {prefix}/{target}")
            continue
        lines += [f"    - {_nav_title(label)}:", f"        - {prefix}/{target}"]
        listing = (root / target).read_text(encoding="utf-8")
        for title, page in INDEX_ENTRY.findall(listing):
            lines.append(f"        - {_nav_title(title)}: {prefix}/{(directory / page).as_posix()}")
    lines.append(f"    - Log: {prefix}/log.md")
    return lines


def splice_navigation(config: str, lines: list[str]) -> str:
    """Return ``config`` with the text between the navigation markers replaced by ``lines``."""
    head, _, rest = config.partition(NAV_BEGIN)
    _, _, tail = rest.partition(NAV_END)
    indent = head[head.rfind("\n") + 1 :]
    body = "".join(f"{indent}{line}\n" for line in lines)
    return f"{head}{NAV_BEGIN}\n{body}{indent}{NAV_END}{tail}"
